const assert = require('assert');
const Board = require('../js/board.js');
const config = require('../js/config.js');
const board = new Board({rows:7,cols:7});
board.grid = Array.from({length:board.rows},()=>Array(board.cols).fill('yellow'));
board.grid[3][3]={c:'red',s:'split'};
const colors=['blue','green','purple','orange'];
config.MATCH_SKILL.splitCorners.forEach(([dr,dc],i)=>{board.grid[3+dr][3+dc]=colors[i];});
let first=true;
board.findMatches=()=>{if(!first)return [];first=false;return [{cells:[[3,3]],shape:'3',color:'red',_noPlant:true}];};
const result=board.resolve();
const steps=result.stepList || result.steps;
const planted=steps[0].planted.filter(p=>p.sub);
assert.deepStrictEqual(planted.map(p=>p.color),colors);
const {deviceInfo}=require('../js/game/account.js');
global.wx={getDeviceInfo:()=>({brand:'HUAWEI',model:'nova',system:'Android'}),getWindowInfo:()=>({windowWidth:360,windowHeight:780,pixelRatio:3,screenWidth:360,screenHeight:800})};
assert.strictEqual(deviceInfo().model,'nova');
assert.strictEqual(deviceInfo().window,'360 × 780');
global.wx={};assert.strictEqual(deviceInfo().model,'未知');
console.log('PASS split children preserve four target colors; device information and missing API fallback');
